import { Router } from 'express';
import { authenticate, authorize } from '../middleware/auth.js';
import * as controller from '../controllers/workoutController.js';
const router = Router();
const staff = authorize('admin', 'trainer');
router.use((_req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
router.use(authenticate, authorize('admin', 'trainer', 'member'));
router.get('/exercises', staff, controller.library('exercises'));
router.post('/exercises', staff, controller.exercise(false));
router.put('/exercises/:id', staff, controller.exercise(true));
router.get('/plans', staff, controller.library('plans'));
router.post('/plans', staff, controller.plan(false));
router.put('/plans/:id', staff, controller.plan(true));
router.post('/plans/:id/assign', staff, controller.assign);
router.get('/members', staff, controller.members);
router.get('/assignments', controller.assignments);
router.get('/assignments/:id', controller.detail);
router.patch('/assignments/:id/completion', authorize('member'), controller.complete);
router.post('/assignments/:id/archive', staff, controller.archive);
export default router;
